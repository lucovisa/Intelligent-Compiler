#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Lang {
    Ru,
    En,
    De,
    Fr,
    Es,
}

impl Lang {
    pub const ALL: [Lang; 5] = [Lang::En, Lang::Ru, Lang::De, Lang::Fr, Lang::Es];

    pub fn label(self) -> &'static str {
        match self {
            Lang::Ru => "Русский",
            Lang::En => "English",
            Lang::De => "Deutsch",
            Lang::Fr => "Français",
            Lang::Es => "Español",
        }
    }

    pub fn code(self) -> &'static str {
        match self {
            Lang::Ru => "ru",
            Lang::En => "en",
            Lang::De => "de",
            Lang::Fr => "fr",
            Lang::Es => "es",
        }
    }

    pub fn from_code(c: &str) -> Option<Lang> {
        Self::ALL.into_iter().find(|l| l.code() == c)
    }

    pub fn system_default() -> Lang {
        let mut locale = std::env::var("LC_ALL")
            .or_else(|_| std::env::var("LC_MESSAGES"))
            .or_else(|_| std::env::var("LANG"))
            .unwrap_or_default();
        if locale.is_empty() {
            #[cfg(target_os = "windows")]
            {
                locale = std::process::Command::new("powershell")
                    .args(["-NoProfile", "-Command", "(Get-Culture).Name"])
                    .output()
                    .ok()
                    .map(|output| String::from_utf8_lossy(&output.stdout).trim().to_string())
                    .unwrap_or_default();
            }
            #[cfg(target_os = "macos")]
            {
                locale = std::process::Command::new("defaults")
                    .args(["read", "-g", "AppleLanguages"])
                    .output()
                    .ok()
                    .map(|output| String::from_utf8_lossy(&output.stdout).to_string())
                    .unwrap_or_default();
            }
            #[cfg(target_os = "linux")]
            {
                locale = std::process::Command::new("locale")
                    .output()
                    .ok()
                    .map(|output| String::from_utf8_lossy(&output.stdout).to_string())
                    .unwrap_or_default();
            }
        }
        let locale = locale.to_lowercase();
        if locale.contains("ru") {
            Lang::Ru
        } else if locale.contains("de") {
            Lang::De
        } else if locale.contains("fr") {
            Lang::Fr
        } else if locale.contains("es") {
            Lang::Es
        } else {
            Lang::En
        }
    }
}

